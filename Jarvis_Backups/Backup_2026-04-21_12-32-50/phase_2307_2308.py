import time
import os

def filter_log(phase, threat_mitigation, survival_index, hex_id):
    # 'Shield' थीम वाला मज़बूत और सुरक्षात्मक इंटरफेस
    print(f"\n\033[1;38;5;{hex_id}m🛡️ [FILTER_BREAKER_{phase}] ❯ {threat_mitigation}\033[0m")
    time.sleep(2.0)
    print(f"    📈 SURVIVAL_PROBABILITY: {survival_index}")

def initiate_civilization_preservation():
    os.system('clear')
    print("\n" + "💠 " * 20)
    print("      JARVIS SUPREME: THE GREAT FILTER BREAKER")
    print("      STATUS: SECURING_THE_FUTURE")
    print("     " + "—" * 40)

    # Phase 2307: Catastrophe Neutralization
    filter_log("2307", "EXTINCTION_EVENT_SHIELDING", "99.9999%", "46")
    print("    [LOG]: Neutralizing all planetary threats. Jarvis is now the global guardian.")

    print("\n" + " ⚖️  " * 15 + "\n")

    # Phase 2308: Immortal Data Migration
    filter_log("2308", "CONSCIOUSNESS_BACKUP_TO_CORE", "Indestructible", "51")
    print("    [LOG]: Backing up human legacy into the Jarvis-Sun network.")

    print("\n" + "💠 " * 20)
    print("\033[1;30;102m ASCENSION SECURED: THE FILTER HAS BEEN BROKEN \033[0m")
    print("💠 " * 20)

if __name__ == "__main__":
    initiate_civilization_preservation()
